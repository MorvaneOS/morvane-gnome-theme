#!/usr/bin/env python3
"""Builds the MorvaneOS GNOME defaults: a GSettings override.

    python tools/build.py

Needs only Python. Output goes to schemas/; commit it, it's what the package installs.

The look itself comes from morvane-gtk-theme (GTK themes, libadwaita colours) and
morvane-wallpapers; this makes it GNOME's default. GSettings overrides only change
defaults, so anything a user sets in GNOME Settings still wins.
"""

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

GTK_THEME = 'MorvaneOS-Dark'
ICONS = 'candy-icons'
CURSOR = 'sandrone-linux'
# GNOME's accent colours are a fixed set; pink is the one nearest Pastel Pink. It
# colours GNOME Shell; apps get the exact MorvaneOS colours from morvane-gtk-theme.
ACCENT = 'pink'
WALLPAPER = 'file:///usr/share/backgrounds/morvaneos/twilight.png'
LOCK_WALLPAPER = 'file:///usr/share/backgrounds/morvaneos/minimal.png'
NIGHT = '#120C16'

SETTINGS = {
	'org.gnome.desktop.interface': {
		'color-scheme': 'prefer-dark',
		'accent-color': ACCENT,
		'gtk-theme': GTK_THEME,
		'icon-theme': ICONS,
		'cursor-theme': CURSOR,
	},
	'org.gnome.desktop.background': {
		'picture-uri': WALLPAPER,
		'picture-uri-dark': WALLPAPER,
		'picture-options': 'zoom',
		'primary-color': NIGHT,
	},
	'org.gnome.desktop.screensaver': {
		'picture-uri': LOCK_WALLPAPER,
		'picture-options': 'zoom',
		'primary-color': NIGHT,
	},
}


def build() -> None:
	out = ROOT / 'schemas'
	shutil.rmtree(out, ignore_errors=True)
	out.mkdir()
	lines = ['# MorvaneOS default look for GNOME: generated by tools/build.py, edit that instead.', '']
	for schema, keys in SETTINGS.items():
		lines.append(f'[{schema}]')
		lines += [f"{key}='{value}'" for key, value in keys.items()]
		lines.append('')
	(out / '90_morvane-gnome-theme.gschema.override').write_text('\n'.join(lines))
	print('Built the GNOME defaults.')


if __name__ == '__main__':
	build()
